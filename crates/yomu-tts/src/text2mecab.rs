mod tests {
    use super::text2mecab;

    #[test]
    fn converts_ascii_and_halfwidth_kana() {
        assert_eq!(text2mecab("A b1 ｶﾞｷﾞｱ\t漢字"), "Ａ　ｂ１　ガギア漢字");
        assert_eq!(text2mecab("ﾊﾟﾟ"), "パ");
    }
}
