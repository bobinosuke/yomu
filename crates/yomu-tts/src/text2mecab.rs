pub fn text2mecab(input: &str) -> String {
    let mut out = String::with_capacity(input.len() * 2);
    let mut rest = input;
    while let Some(c) = rest.chars().next() {
        if let Some((from, to)) = CONV.iter().find(|(from, _)| rest.starts_with(from)) {
            out.push_str(to);
            rest = &rest[from.len()..];
        } else {
            if !c.is_ascii() {
                out.push(c); // 表にない ASCII は制御文字なので捨てる
            }
            rest = &rest[c.len_utf8()..];
        }
    }
    out
}

